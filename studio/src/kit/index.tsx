import React from "react";
import { AbsoluteFill } from "remotion";
import { AudioManifest, Film, ShotPlan, Storyboard } from "../lib/Film";
import { Captions, Word } from "./Captions";
import { SCENES } from "./scenes";

/*
  KIT FILM — a film made only from storyboard.json. Each shot names a kit scene and
  its props, plus the line to say. make.py makes the voice + word timings (captions.json)
  and the music (music/score.mp3); shots grow to fit their line.
*/

export const SAY_AT = 0.3; // seconds into the shot where the line starts (kit_tts.py uses the same)
const TAIL = 0.45; // breath after the line before the cut (kit_tts.py uses the same)
const MUSIC_VOLUME = 0.22;

export type KitCaptions = Record<string, { dur: number; words: { text: string; start: number; end: number }[] }>;

export const kitStoryboard = (raw: Storyboard, captions: KitCaptions): Storyboard => {
  const shots = raw.shots.map((s, i) => {
    if (!s.scene || !(s.scene in SCENES)) throw new Error(`shot ${s.id}: scene "${s.scene}" is unknown. Use one of: ${Object.keys(SCENES).join(", ")}`);
    const dur = s.say ? captions[s.id]?.dur ?? 0 : 0;
    return {
      ...s,
      beat: s.beat ?? i + 1,
      kind: s.kind ?? "story",
      what: s.what ?? s.say ?? s.scene,
      seconds: Math.max(s.seconds, s.say ? SAY_AT + dur + TAIL : 0),
      narration: s.say ? [{ at: SAY_AT, text: s.say, startSec: SAY_AT, endSec: SAY_AT + dur }] : s.narration,
    } as ShotPlan;
  });
  const total = shots.reduce((a, s) => a + s.seconds, 0);
  // the generated score plays under the whole film (Film skips it if make.py has not made it yet)
  return { ...raw, shots, music: raw.music ?? [{ name: "score", startSec: 0, endSec: total, volume: MUSIC_VOLUME }] };
};

const kitShots = (sb: Storyboard) =>
  Object.fromEntries(sb.shots.map((s) => {
    const Scene = SCENES[s.scene as keyof typeof SCENES];
    const props = s.props ?? {};
    return [s.id, () => <Scene {...props} />];
  })) as Record<string, React.FC>;

const kitWords = (sb: Storyboard, captions: KitCaptions) => {
  const out: Word[] = [];
  let cursor = 0;
  for (const s of sb.shots) {
    for (const w of s.say ? captions[s.id]?.words ?? [] : []) {
      out.push({ text: w.text, from: cursor + Math.round((SAY_AT + w.start) * sb.fps), to: cursor + Math.round((SAY_AT + w.end) * sb.fps) });
    }
    cursor += Math.round(s.seconds * sb.fps);
  }
  return out;
};

// One call per film folder (index.tsx is generated by make.py).
export const kitFilm = (storyboard: unknown, audio: unknown, captions: unknown) => {
  const sb = kitStoryboard(storyboard as Storyboard, captions as KitCaptions);
  const shots = kitShots(sb);
  const words = kitWords(sb, captions as KitCaptions);
  const component: React.FC<{ muted?: boolean }> = ({ muted }) => (
    <AbsoluteFill>
      <Film storyboard={sb} shots={shots} audio={audio as AudioManifest} muted={muted} />
      {!muted && <Captions words={words} />}
    </AbsoluteFill>
  );
  return { component, storyboard: sb };
};
